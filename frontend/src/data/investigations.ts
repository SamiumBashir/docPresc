/**
 * Search all 335 investigations by keyword, acronym or category
 */
export const searchInvestigations = (query: string): InvestigationItem[] => {
  if (!query || !query.trim()) return [];
  const q = query.toLowerCase().trim();

  return INVESTIGATIONS_DATA.filter((item) => {
    if (item.name.toLowerCase().includes(q)) return true;
    if (item.category.toLowerCase().includes(q)) return true;
    if (item.aliases && item.aliases.some((a) => a.toLowerCase().includes(q))) return true;
    return false;
  }).slice(0, 20);
};
