/**
 * Search diagnoses by name, ICD-10 code, category, or Bangla aliases
 */
export const searchDiagnoses = (query: string): DiagnosisItem[] => {
  if (!query || !query.trim()) return [];
  const q = query.toLowerCase().trim();

  return DIAGNOSES_DATA.filter((item) => {
    if (item.name.toLowerCase().includes(q)) return true;
    if (item.icdCode && item.icdCode.toLowerCase().includes(q)) return true;
    if (item.category.toLowerCase().includes(q)) return true;
    if (item.aliases && item.aliases.some((a) => a.toLowerCase().includes(q))) return true;
    return false;
  }).slice(0, 20);
};
